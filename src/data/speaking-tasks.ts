/** Builds the 3-part structure with the standard 2/3/3-minute timing. */
function task(
  id: string, level: SpeakingTask["level"], title: string, topic: string,
  intro: [string, string], main: [string, string], disc: [string, string],
): SpeakingTask {
  return {
    id, level, title, topic,
    parts: [
      { instruction: intro[0], instructionRu: intro[1], timeMinutes: 2 },
      { instruction: main[0], instructionRu: main[1], timeMinutes: 3 },
      { instruction: disc[0], instructionRu: disc[1], timeMinutes: 3 },
    ],
  };
}

