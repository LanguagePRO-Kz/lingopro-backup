-- ---------------------------------------------------------------------
-- 0015: пропуск вопроса (Фаза 4 финального захода).
--
-- «Не знаю» и неверный ответ — разные сигналы: незнание ≠ угадывание,
-- агент обязан их различать (ТЗ Фазы 4 п.1). skipped=true всегда идёт
-- с is_correct=false; расчёты точности пропуски не искажают (это честные
-- «не знаю»), а скорость закрытия темы агент может считать отдельно.
--
-- Применяется ДО деплоя кода Фазы 4: /api/attempts начинает писать
-- колонку (батч диагностики и обычные попытки с кнопкой «Не знаю»).
-- ---------------------------------------------------------------------

alter table attempts add column if not exists skipped boolean not null default false;

comment on column attempts.skipped is
  'Студент нажал «Не знаю» (незнание), а не выбрал неверный вариант (угадывание). Всегда вместе с is_correct=false.';
